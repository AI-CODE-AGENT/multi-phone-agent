"""
Code Improver & Patch Generator Subagent
Takes defects, crashes, or performance bottlenecks identified by the Auditor,
analyzes the code context, generates standard unified Git patches (.patch / .diff),
and records them in the Codebase Memory for automated regression testing.
"""

import os
import sys
import time
import difflib
from pathlib import Path
from typing import Dict, List, Optional, Any, Tuple

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from core.memory_manager import MemoryManager
from core.git_worktree_manager import GitWorktreeManager

REPORTS_DIR = Path(__file__).resolve().parent.parent / "reports"
PATCHES_DIR = REPORTS_DIR / "patches"


class CodeImproverSubagent:
    def __init__(self, memory: Optional[MemoryManager] = None, worktree_mgr: Optional[GitWorktreeManager] = None):
        self.memory = memory or MemoryManager()
        self.worktree_mgr = worktree_mgr or GitWorktreeManager()
        PATCHES_DIR.mkdir(parents=True, exist_ok=True)

    def generate_unified_patch(
        self,
        file_path: str,
        original_content: str,
        improved_content: str,
        defect_id: str,
        summary: str
    ) -> Tuple[str, Path]:
        """
        Generate a unified diff patch file compatible with 'git apply'.
        """
        original_lines = original_content.splitlines(keepends=True)
        improved_lines = improved_content.splitlines(keepends=True)

        patch_lines = list(difflib.unified_diff(
            original_lines,
            improved_lines,
            fromfile=f"a/{file_path}",
            tofile=f"b/{file_path}",
            lineterm="\n"
        ))
        diff_text = "".join(patch_lines)

        timestamp = time.strftime("%Y%m%d_%H%M%S")
        patch_filename = f"patch_{defect_id}_{timestamp}.diff"
        patch_file = PATCHES_DIR / patch_filename

        with open(patch_file, "w", encoding="utf-8") as f:
            f.write(f"# Unified Git Patch generated by CodeImproverSubagent\n")
            f.write(f"# Defect ID: {defect_id}\n")
            f.write(f"# Summary: {summary}\n")
            f.write(f"# Generated: {time.strftime('%Y-%m-%d %H:%M:%S')}\n\n")
            f.write(diff_text)

        # Record in memory
        self.memory.record_patch(
            defect_id=defect_id,
            target_file=file_path,
            diff_content=diff_text,
            explanation=summary,
            verified=False
        )

        return diff_text, patch_file

    def analyze_defect_and_propose_patch(
        self,
        defect: Dict[str, Any],
        repo_root: Optional[Path] = None
    ) -> Dict[str, Any]:
        """
        Analyze a detected defect (e.g. NullPointerException, ANR, unhandled timeout)
        and construct an automated patch.
        """
        defect_id = defect.get("defect_id", f"DEF_{int(time.time())}")
        defect_type = defect.get("defect_type", "GENERIC_ERROR")
        title = defect.get("title", "App Issue")
        stack_trace = defect.get("stack_trace", "")
        context = defect.get("context", {})

        # Example auto-remediation templates based on defect types:
        if "nullpointer" in defect_type.lower() or "npe" in title.lower():
            target_file = "src/main/java/com/app/auth/AuthManager.java"
            orig = """    public void onOtpReceived(String code) {
        otpTextView.setText(code);
        verifyButton.setEnabled(true);
    }
"""
            improved = """    public void onOtpReceived(String code) {
        if (code == null || code.trim().isEmpty()) {
            Log.w("AuthManager", "Received empty or null OTP code. Ignoring.");
            return;
        }
        if (otpTextView != null) {
            otpTextView.setText(code);
        }
        if (verifyButton != null) {
            verifyButton.setEnabled(true);
        }
    }
"""
            summary = "Added null checks for code parameter, otpTextView, and verifyButton to prevent NPE."

        elif "latency" in defect_type.lower() or "jank" in defect_type.lower():
            target_file = "src/main/java/com/app/ui/HomeScreen.kt"
            orig = """    fun loadFeedData() {
        val data = networkClient.fetchDataSync()
        adapter.submitList(data)
    }
"""
            improved = """    fun loadFeedData() {
        viewModelScope.launch(Dispatchers.IO) {
            val data = networkClient.fetchData()
            withContext(Dispatchers.Main) {
                adapter.submitList(data)
            }
        }
    }
"""
            summary = "Shifted synchronous network fetch from Main thread to Dispatchers.IO to eliminate 16ms+ frame drops (ANR avoidance)."

        else:
            target_file = "src/main/java/com/app/network/ApiClient.kt"
            orig = """    fun executeRequest() {
        // Standard call without timeout
        client.newCall(request).execute()
    }
"""
            improved = """    fun executeRequest() {
        // Configured resilient timeouts: connect 5s, read 10s
        val resilientClient = client.newBuilder()
            .connectTimeout(5, TimeUnit.SECONDS)
            .readTimeout(10, TimeUnit.SECONDS)
            .build()
        resilientClient.newCall(request).execute()
    }
"""
            summary = "Added explicit socket and read timeouts to prevent infinite UI hangs."

        diff_text, patch_file = self.generate_unified_patch(
            file_path=target_file,
            original_content=orig,
            improved_content=improved,
            defect_id=defect_id,
            summary=summary
        )

        return {
            "status": "PATCH_CREATED",
            "defect_id": defect_id,
            "target_file": target_file,
            "patch_file": str(patch_file),
            "summary": summary,
            "diff_preview": diff_text[:500]
        }

    def develop_feature_in_worktree(
        self,
        feature_slug: str,
        subagent_name: str,
        target_rel_path: str,
        file_content: str,
        commit_message: str
    ) -> Dict[str, Any]:
        """
        Create an isolated Git worktree for a specific feature, write the feature module/patch
        inside that worktree, and commit atomically on branch `feat/<feature_slug>`.
        """
        wt_info = self.worktree_mgr.create_feature_worktree(
            feature_name=feature_slug,
            subagent_name=subagent_name,
            base_branch="main",
            branch_prefix="feat"
        )
        if not wt_info.get("success"):
            return wt_info

        wt_root = Path(wt_info["worktree_path"])
        dest_file = wt_root / target_rel_path
        dest_file.parent.mkdir(parents=True, exist_ok=True)
        dest_file.write_text(file_content, encoding="utf-8")

        commit_res = self.worktree_mgr.commit_in_worktree(
            worktree_path=wt_root,
            commit_message=commit_message,
            subagent_name=subagent_name
        )
        return {
            "success": commit_res.get("success", False),
            "subagent": subagent_name,
            "feature_slug": wt_info["feature_slug"],
            "branch": wt_info["branch"],
            "worktree_path": str(wt_root),
            "target_file": str(dest_file),
            "commit": commit_res
        }


